                         THEN C.CODPARCDEST
                     ELSE C.CODPARC
                    END = E1.CODPARC
          AND   E1.TIPO = CASE when I.ATUALESTTERC IN ('T','D') THEN 'T' ELSE 'P' END
    )
GROUP BY I.CODEMP, EMP.CODLOCALTERC, I.CODPROD, CASE when NVL(I.TERCEIROS,'N') = 'N' THEN I.CODLOCALORIG ELSE NVL(I.CODLOCALTERC,I.CODLOCALORIG) END, I.CONTROLE
       , CASE WHEN C.CODPARCDEST <> 0 AND
