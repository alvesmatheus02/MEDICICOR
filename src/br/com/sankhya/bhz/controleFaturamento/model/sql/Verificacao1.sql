    (
        SELECT 1 FROM TGFEST E1
        WHERE E1.CODEMP   = I.CODEMP
          AND   E1.CODPROD  = I.CODPROD
          AND   E1.CODLOCAL = CASE when NVL(I.TERCEIROS,'N') = 'N' THEN I.CODLOCALORIG ELSE NVL(I.CODLOCALTERC,I.CODLOCALORIG) END
