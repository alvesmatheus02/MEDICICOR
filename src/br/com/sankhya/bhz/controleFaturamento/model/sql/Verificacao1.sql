  AND I.CODEMP   > 0
  AND I.CODEMP = EMP.CODEMP
  AND I.CODPROD  IN (:CODPROD)
  AND I.CONTROLE  IN (:CONTROLE)
  AND I.NUNOTA >= 0
  AND I.CODPROD = P.CODPROD
  AND I.ATUALESTTERC IN ('P','T','R','D')
  AND I.NUNOTA = C.NUNOTA
  AND T.CODTIPOPER = C.CODTIPOPER
  AND T.DHALTER = C.DHTIPOPER


