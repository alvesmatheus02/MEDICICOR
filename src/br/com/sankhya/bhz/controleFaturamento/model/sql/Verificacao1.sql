SELECT
    CAST(I.CODEMP AS FLOAT) AS CODEMP,
    CAST(EMP.CODLOCALTERC AS FLOAT) AS CODLOCALTERC,
    CAST(I.CODPROD AS FLOAT) AS CODPROD,
    CAST(E.CODLOCAL AS FLOAT) AS CODLOCAL,
    CAST(0 AS FLOAT) AS CODPARC,
    'P' AS TIPO,
    E.CONTROLE,
    ROUND(SUM(CASE WHEN P.USOPROD = 'S' THEN 0 ELSE ((I.QTDNEG)* I.ATUALESTOQUE) END),9) AS CENTRAL,
    ROUND(CAST(E.ESTOQUE AS FLOAT),9) AS ESTOQUE,
    0 AS RESERVADO,
    0 AS OFICIAL,
    1 AS VERIFICACAO
FROM TGFITE I
   , TGFEST E
   , TGFPRO P
   , TGFEMP EMP
WHERE   I.RESERVA = 'N'
  AND E.CODEMP   > 0
  AND EMP.CODEMP = E.CODEMP
  AND E.CODPROD  IN (:CODPROD)
  AND I.CONTROLE  IN (:CONTROLE)
  AND I.CODEMP  = E.CODEMP
  AND I.CODPROD = E.CODPROD
  AND I.CODLOCALORIG = E.CODLOCAL
  AND I.CONTROLE = E.CONTROLE
  AND E.CODPARC = 0
  AND I.NUNOTA >= 0
  AND I.CODPROD = P.CODPROD
  AND I.ATUALESTOQUE <> 0
  AND P.USOPROD <> 'S'

GROUP BY I.CODEMP, EMP.CODLOCALTERC, I.CODPROD, E.CODLOCAL, E.CONTROLE, E.ESTOQUE, P.DECQTD
HAVING  ROUND(ABS(ROUND(SUM(CASE WHEN P.USOPROD = 'S' THEN 0 ELSE ((I.QTDNEG)* I.ATUALESTOQUE) END),9) - ROUND(E.ESTOQUE,9)), 9) >= 0.00001

UNION ALL

