                   I.ATUALESTTERC IN ('P','T') AND
                   (NVL(T.CODCFO_ENTRADA,0) IN (1122,2122) OR
                    NVL(T.CODCFO_ENTRADA_FORA,0) IN (1122,2122))
                  THEN C.CODPARCDEST
              ELSE C.CODPARC
        END AS FLOAT) AS CODPARC,
    CASE WHEN I.ATUALESTTERC IN ('T','D') THEN 'T' ELSE 'P' END AS TIPO,
    I.CONTROLE,
    ROUND(SUM(I.QTDNEG * CASE WHEN I.ATUALESTTERC IN ('P', 'T') THEN 1 ELSE -1 END * CASE WHEN I.SEQUENCIA > 0 THEN 1 ELSE -1 END), 9) AS CENTRAL,
    CAST(0.000000000 AS FLOAT) AS ESTOQUE,
    0 AS RESERVADO,
    0 AS OFICIAL,
    1 AS VERIFICACAO
FROM TGFITE I
   , TGFPRO P
   , TGFCAB C
   , TGFTOP T
   , TGFEMP EMP
